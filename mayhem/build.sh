#!/usr/bin/env bash
#
# mayhem/build.sh — build pForth: the in-process libFuzzer harness, its standalone
# reproducer, AND the project's own test-suite binary.
#
# pForth builds via platforms/unix/Makefile:
#   pforth            = bootstrap interpreter (compiled from C)
#   pforth.dic        = dictionary built by running pforth over fth/system.fth
#   pfdicdat.h        = dictionary image header (embedded when PF_STATIC_DIC)
#   pforth_standalone = final interpreter with the dictionary embedded
#
# The fuzz TARGET is NOT the CLI binary — the raw CLI (`pforth_standalone @@`) could not be
# instrumented by Mayhem (0 edges). Instead we compile an in-process libFuzzer harness
# (mayhem/pforth_fuzzer.c) that calls pfInitialize()/pfInterpretText()/pfTerminate() over the
# same interpreter code path, linked against the embedded-dictionary (PF_STATIC_DIC) objects.
#
# Builds performed:
#   1) TEST build  — project's normal flags → mayhem/out/pforth_standalone_test (for test.sh)
#   2) pfdicdat.h  — generated by the bootstrap interpreter (needed by the PF_STATIC_DIC build)
#   3) FUZZ build  — every embedded object (minus pf_main.o, which carries main()) instrumented
#      with $SANITIZER_FLAGS + coverage, linked with the libFuzzer engine → /mayhem/pforth_fuzzer
#   4) STANDALONE  — same objects + harness linked against $STANDALONE_FUZZ_MAIN → /mayhem/pforth_fuzzer-standalone
set -euo pipefail

[ -n "${SOURCE_DATE_EPOCH:-}" ] || unset SOURCE_DATE_EPOCH

: "${SANITIZER_FLAGS=-fsanitize=address,undefined -fno-sanitize-recover=all -fno-omit-frame-pointer}"
: "${DEBUG_FLAGS:=-g -gdwarf-3}"
: "${CC:=clang}" ; : "${CXX:=clang++}" ; : "${LIB_FUZZING_ENGINE:=-fsanitize=fuzzer}"
: "${STANDALONE_FUZZ_MAIN:=/opt/mayhem/StandaloneFuzzTargetMain.c}"
: "${MAYHEM_JOBS:=$(nproc)}"
: "${COVERAGE_FLAGS=}"
export SANITIZER_FLAGS DEBUG_FLAGS CC CXX LIB_FUZZING_ENGINE STANDALONE_FUZZ_MAIN MAYHEM_JOBS COVERAGE_FLAGS

cd "$SRC"
UNIXDIR="$SRC/platforms/unix"
CSRC="$SRC/csrc"
mkdir -p "$SRC/mayhem/out"

# 1) TEST build: project's NORMAL flags (independent of the sanitized build) so mayhem/test.sh
#    only RUNS the suite. COVERAGE_FLAGS (empty by default) instruments it for coverage measurement.
make -C "$UNIXDIR" clean
make -C "$UNIXDIR" -j"$MAYHEM_JOBS" all CC="$CC" \
    EXTRA_CCOPTS="$COVERAGE_FLAGS" XLDFLAGS="$COVERAGE_FLAGS"
cp "$UNIXDIR/pforth_standalone" "$SRC/mayhem/out/pforth_standalone_test"

# 2) Generate pfdicdat.h (the embedded static dictionary) using the freshly-built bootstrap
#    interpreter. `make pfdicdat` leaves pfdicdat.h in $UNIXDIR. Keep a normal-flags bootstrap
#    for this step (the dictionary image is interpreter-output, not sanitized code).
make -C "$UNIXDIR" clean
make -C "$UNIXDIR" -j"$MAYHEM_JOBS" pfdicdat CC="$CC"
test -f "$UNIXDIR/pfdicdat.h"

# 3) FUZZ build. Compile every pForth translation unit that the embedded (PF_STATIC_DIC) build
#    uses — EXCEPT pf_main.c, whose main() would clash with the libFuzzer/standalone driver —
#    with $SANITIZER_FLAGS, DWARF-3 debug info, and libFuzzer coverage. Flags mirror the
#    Makefile's embedded compile (EMBCCOPTS=-DPF_STATIC_DIC, FPOPTS=-DPF_SUPPORT_FP).
PF_SRCS=(
    "$CSRC/pf_cglue.c" "$CSRC/pf_clib.c" "$CSRC/pf_core.c" "$CSRC/pf_inner.c"
    "$CSRC/pf_io.c" "$CSRC/pf_io_none.c" "$CSRC/pf_mem.c" "$CSRC/pf_save.c"
    "$CSRC/pf_text.c" "$CSRC/pf_words.c" "$CSRC/pfcompil.c" "$CSRC/pfcustom.c"
    "$CSRC/paging/pagedmem.c" "$CSRC/paging/lockpage.c" "$CSRC/paging/qadmpage.c"
    "$CSRC/posix/pf_io_posix.c" "$CSRC/stdio/pf_fileio_stdio.c"
)

# Compile flags: -x c so clang treats the (extension-correct) sources as C; PF_STATIC_DIC embeds
# the dictionary; PF_SUPPORT_FP matches the default float build; -I$UNIXDIR puts the generated
# pfdicdat.h on the include path (pf_save.c does #include "pfdicdat.h"); -I$CSRC for the headers.
CFLAGS_COMMON=(
    -x c -O1 -DPF_STATIC_DIC -DPF_SUPPORT_FP -D_DEFAULT_SOURCE -D_GNU_SOURCE
    -I"$UNIXDIR" -I"$CSRC"
    $SANITIZER_FLAGS $DEBUG_FLAGS
)

OBJDIR="$SRC/mayhem/obj"
rm -rf "$OBJDIR"; mkdir -p "$OBJDIR"
objs=()
for src in "${PF_SRCS[@]}"; do
    obj="$OBJDIR/$(echo "$src" | sed "s#$SRC/##; s#/#_#g").o"
    "$CC" "${CFLAGS_COMMON[@]}" -fsanitize=fuzzer-no-link -c "$src" -o "$obj"
    objs+=("$obj")
done

# Harness object (also needs the embedded-dictionary defines + include paths).
"$CC" "${CFLAGS_COMMON[@]}" -fsanitize=fuzzer-no-link \
    -c "$SRC/mayhem/pforth_fuzzer.c" -o "$OBJDIR/pforth_fuzzer.o"

# Link the libFuzzer target.
"$CC" $SANITIZER_FLAGS $DEBUG_FLAGS $LIB_FUZZING_ENGINE \
    "$OBJDIR/pforth_fuzzer.o" "${objs[@]}" -lm -o /mayhem/pforth_fuzzer

# 4) STANDALONE reproducer: same objects + harness, linked against the run-once driver instead of
#    the libFuzzer engine (one input file, natural crash, no libFuzzer runtime).
"$CC" $SANITIZER_FLAGS $DEBUG_FLAGS -c "$STANDALONE_FUZZ_MAIN" -o "$OBJDIR/standalone_main.o"
"$CC" $SANITIZER_FLAGS $DEBUG_FLAGS \
    "$OBJDIR/standalone_main.o" "$OBJDIR/pforth_fuzzer.o" "${objs[@]}" -lm \
    -o /mayhem/pforth_fuzzer-standalone

ls -l /mayhem/pforth_fuzzer /mayhem/pforth_fuzzer-standalone "$SRC/mayhem/out/pforth_standalone_test"
